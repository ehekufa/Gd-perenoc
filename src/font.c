static const Glyph *find_glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    for (size_t i = 0; i < SDL_arraysize(kGlyphs); i++) {
        if (kGlyphs[i].c == c) {
            return &kGlyphs[i];
        }
    }
    return NULL;
}

float font_height(float scale) { return 7.0f * scale; }

float font_width(float scale, const char *text)
{
    float w = 0.0f;
    for (const char *p = text; *p; p++) {
        w += 6.0f * scale;
    }
    return w > 0.0f ? w - scale : 0.0f;
}

static void font_draw_ex(SDL_Renderer *ren, float x, float y, float scale,
                         const char *text, SDL_Color color, float ox, float oy)
{
    SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(ren, color.r, color.g, color.b, color.a);
    float cx = x + ox;
    for (const char *p = text; *p; p++) {
        const Glyph *g = find_glyph(*p);
        if (g) {
            for (int row = 0; row < 7; row++) {
                for (int col = 0; col < 5; col++) {
                    if (g->rows[row] & (1 << (4 - col))) {
                        SDL_FRect r = { cx + col * scale, y + oy + row * scale, scale + 0.5f, scale + 0.5f };
                        SDL_RenderFillRect(ren, &r);
                    }
                }
            }
        }
        cx += 6.0f * scale;
    }
}

void font_draw(SDL_Renderer *ren, float x, float y, float scale,
               const char *text, SDL_Color color)
{
    font_draw_ex(ren, x, y, scale, text, color, 0.0f, 0.0f);
}

void font_draw_shadow(SDL_Renderer *ren, float x, float y, float scale,
                      const char *text, SDL_Color color)
{
    SDL_Color shadow = { 0, 0, 0, (Uint8)(color.a / 2) };
    float d = SDL_max(2.0f, scale);
    font_draw_ex(ren, x, y, scale, text, shadow, d, d);
    font_draw_ex(ren, x, y, scale, text, color, 0.0f, 0.0f);
}
